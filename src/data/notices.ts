/**
 * The notices of the bar at the top of the home page: the calendar Carinova wrote on 2026-11-18.
 * Each one is a day of the year (a fixed date, the n-th weekday of a month or Easter), the days
 * around it that the notice shows, and its words (`landing.ann` in the dictionaries). The dates
 * work themselves out every year (utils/notices.ts).
 *
 * - `window`: from how many days before the day (negative) to how many after. "sea" and "air"
 *   stand for the last day a package can reach the warehouse to arrive by that way in time: the
 *   longest delivery time of RATES plus NOTICE_BUFFER_DAYS for customs. "sea+1" is the day after.
 * - `chip`: what is said beside the text. "cutoffs": those last days, by sea and by air; "sea" or
 *   "air": one of them; "anchor" and "holiday": the day itself is named after the title (with
 *   `offsets`, the days from it that count: a holiday of two days); "none".
 * - `cta`: where its link leads: the stores ("shopper"), the calculator, or nowhere.
 * - `enabled`: whether the site shows it. The closures (Holy Week, the national holidays of
 *   article 66 of the Código del Trabajo) are off: turn one on if the branches close that day.
 * - `estimated`: the day is a guess until the store announces it (Prime Day): check it each year.
 * - `dated`: the title carries the date of the day ("Día de las Madres · 30 de mayo").
 *
 * When two are on the same day, the higher `priority` shows first. There is no panel to edit
 * them: this file is where a notice is turned on or off, changed or added, and a notice shows
 * from the next deploy.
 *
 * No imports: the unit tests run this file on plain Node.
 */
export type NoticeKind = 'promo' | 'deadline' | 'info' | 'closure';
export type NoticeChip = 'cutoffs' | 'sea' | 'air' | 'anchor' | 'holiday' | 'none';
export type NoticeCta = 'none' | 'calculator' | 'shopper';

export type NoticeRule =
  | { type: 'fixed'; month: number; day: number }
  /** The n-th `weekday` (0 Sunday … 6 Saturday) of a month, -1 for the last; `shift` days after it. */
  | { type: 'nth'; month: number; weekday: number; n: number; shift?: number }
  | { type: 'easter' };

export interface Notice {
  id: string;
  kind: NoticeKind;
  rule: NoticeRule;
  window: { from: number | string; to: number | string };
  chip: NoticeChip;
  offsets: Array<number>;
  cta: NoticeCta;
  priority: number;
  enabled: boolean;
  estimated: boolean;
  /** The names of its title and of its text in `landing.ann`. */
  title: string;
  text: string;
  dated?: boolean;
}

